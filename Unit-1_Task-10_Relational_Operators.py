# Python Comparison Operators Exercise

a = 10
b = 5

# 1. Greater than
result = a > b
print("result of", a, ">", b, "is:", result)

# 2. Less than
result = a < b
print("result of", a, "<", b, "is:", result)

# 3. Greater than or equal to
result = a >= b
print("result of", a, ">=", b, "is:", result)

# 4. Less than or equal to
result = a <= b
print("result of", a, "<=", b, "is:", result)

# 5. Equal to
result = a == b
print("result of", a, "==", b, "is:", result)

# 6. Not equal to
result = a != b
print("result of", a, "!=", b, "is:", result)
